# Helper function to convert LaTeX to clean text for WeChat Mini Program
def latex_to_text(t):
    if not t: return t
    t = t.replace(r'\frac{a-c}{b}', '(a - c) / b')
    t = t.replace(r'\frac{2(a-c)}{3b}', '2(a - c) / (3b)')
    t = t.replace(r'\frac{a-c}{2b}', '(a - c) / (2b)')
    t = t.replace(r'\frac{3(a-c)}{4b}', '3(a - c) / (4b)')
    t = t.replace(r'\frac{1}{2}', '1/2')
    t = t.replace(r'\frac{P-MC}{P}', '(P-MC)/P')
    t = t.replace(r'\frac{A}{PQ}', 'A / (P × Q)')
    t = t.replace(r'\frac{A}{P Q}', 'A / (P × Q)')
    t = t.replace(r'\frac{\epsilon_A}{|\eta|}', 'ε_A / |η|')
    t = t.replace(r'\frac{1}{|\eta|}', '1/|η|')
    t = t.replace(r'\frac{1}{|\eta_1|}', '1/|η₁|')
    t = t.replace(r'\frac{1}{|\eta_2|}', '1/|η₂|')
    t = t.replace(r'q_1^* = q_2^* = \frac{a-c}{3b}', 'q₁* = q₂* = (a - c) / (3b)')
    t = t.replace(r'Q^* = q_1^* + q_2^* = \frac{2(a-c)}{3b}', 'Q* = q₁* + q₂* = 2(a - c) / (3b)')
    t = t.replace(r'\Delta P \cdot \Delta Q', 'ΔP × ΔQ')
    t = t.replace(r'q_1 + q_2', 'q₁ + q₂')
    t = t.replace(r'q_2(q_1)', 'q₂(q₁)')
    t = t.replace(r'n^*', 'n*')
    t = t.replace(r'n^{soc}', 'n_soc')
    t = t.replace(r'P_1 = P_2 = MC', 'P₁ = P₂ = MC')
    t = t.replace(r'P_1 < P_2', 'P₁ < P₂')
    t = t.replace(r'P_1 > P_2', 'P₁ > P₂')
    t = t.replace(r'P_1 = P_2', 'P₁ = P₂')
    t = t.replace(r'|\eta_1| > |\eta_2|', '|η₁| > |η₂|')
    t = t.replace(r'\epsilon_A', 'ε_A')
    t = t.replace(r'|\eta|', '|η|')
    t = t.replace(r'\sum_{i=1}^n S_i^2', '∑ Sᵢ²')
    t = t.replace(r'\sum s_i^2', '∑ Sᵢ²')
    t = t.replace(r'MC < ATC', 'MC < ATC')
    t = t.replace(r'P = ATC', 'P = ATC')
    t = t.replace(r'P = MC', 'P = MC')
    t = t.replace(r'MR = P', 'MR = P')
    t = t.replace(r'Q_L', 'Q_L')
    t = t.replace(r'CPI - X', 'CPI - X')
    t = t.replace('$', '')
    return t

